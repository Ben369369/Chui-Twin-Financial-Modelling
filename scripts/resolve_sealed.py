"""Score every sealed forecast against the reported outcome, once the company has reported.

    python scripts/resolve_sealed.py            # prints results, writes docs/sealed_results.md

For each file in forecasts/sealed/ it:
  1. recomputes the SHA-256 and checks it against the digest in the file name,
  2. finds ground truth for each forecast KPI and period, and accepts it only if it became
     available after the seal (an outcome known before sealing would make the test worthless),
  3. scores the twin (CRPS of its Gaussian summary, 80% interval hit, error of the median)
     against guidance and the two naive baselines, each known at sealing time.

Baselines are point forecasts here, so their CRPS is their absolute error. Run ingest or
run_daily.py first so the reported quarter is in the ground-truth table.
"""

from __future__ import annotations

import json
import sys
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from engine.evaluation.metrics import crps_gaussian  # noqa: E402
from engine.periods import shift  # noqa: E402
from engine.sealing import verify  # noqa: E402
from storage import db  # noqa: E402

SEALED = ROOT / "forecasts" / "sealed"
OUT = ROOT / "docs" / "sealed_results.md"


def known_at(truth: dict, kpi: str, period: str, when: datetime) -> float | None:
    g = truth.get((kpi, period))
    return g.value if g is not None and g.available_at <= when else None


def resolve(path: Path, conn) -> list[dict]:
    rec = json.loads(path.read_text(encoding="utf-8"))
    digest = verify(path)
    hash_ok = digest.startswith(path.stem.rsplit("_", 1)[-1])
    sealed_at = datetime.fromisoformat(rec["sealed_at"])
    truth = {(g.kpi, g.period): g for g in db.load_ground_truth(conn, rec["ticker"])}
    guidance = {(g["kpi"], g["period"]): g["expectation"] for g in rec["expectation_gaps"] if g["source"] == "guidance"}
    rows = []
    for kpi, by_period in rec["forecast"].items():
        for period, f in sorted(by_period.items()):
            row = {"file": path.name, "hash_ok": hash_ok, "ticker": rec["ticker"], "kpi": kpi, "period": period,
                   "sealed_at": rec["sealed_at"], "p10": f["p10"], "p50": f["p50"], "p90": f["p90"], "status": "pending"}
            g = truth.get((kpi, period))
            if g is not None and g.available_at <= sealed_at:
                row["status"] = "invalid: outcome was public before the seal"
            elif g is not None:
                y = g.value
                baselines = {"guidance": guidance.get((kpi, period)),
                             "last quarter": known_at(truth, kpi, shift(period, -1), sealed_at),
                             "last year": known_at(truth, kpi, shift(period, -4), sealed_at)}
                row.update(status="resolved", actual=y, source_ref=g.source_ref, inside_80=f["p10"] <= y <= f["p90"],
                           median_error=f["p50"] - y, crps=crps_gaussian(f["mean"], f["sd"], y),
                           baselines={k: abs(v - y) for k, v in baselines.items() if v is not None})
            rows.append(row)
    return rows


def to_markdown(rows: list[dict]) -> str:
    lines = ["# Sealed forecast results", "",
             "Generated by `scripts/resolve_sealed.py`. Each outcome is accepted only if it became public after "
             "the seal. Twin CRPS uses the sealed mean and sd; baselines are points, so their CRPS is absolute "
             "error. Lower is better.", "",
             "| Twin | KPI | Period | Sealed 80% range | Median | Actual | Inside 80% | Twin CRPS | Guidance | Last quarter | Last year | Hash |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        if r["status"] != "resolved":
            lines.append(f"| {r['ticker']} | {r['kpi']} | {r['period']} | {r['p10']:.1f} to {r['p90']:.1f} | {r['p50']:.1f} "
                         f"| {r['status']} | | | | | | {'ok' if r['hash_ok'] else 'MISMATCH'} |")
            continue
        b = r["baselines"]
        cell = lambda k: f"{b[k]:.2f}" if k in b else "–"  # noqa: E731
        lines.append(f"| {r['ticker']} | {r['kpi']} | {r['period']} | {r['p10']:.1f} to {r['p90']:.1f} | {r['p50']:.1f} "
                     f"| {r['actual']:.1f} | {'yes' if r['inside_80'] else 'no'} | {r['crps']:.2f} | {cell('guidance')} "
                     f"| {cell('last quarter')} | {cell('last year')} | {'ok' if r['hash_ok'] else 'MISMATCH'} |")
    lines += ["", "Outcome sources:", ""]
    lines += [f"- {r['ticker']} {r['kpi']} {r['period']}: {r['source_ref']}" for r in rows if r["status"] == "resolved"]
    return "\n".join(lines) + "\n"


def main() -> None:
    conn = db.connect()
    rows = [r for p in sorted(SEALED.glob("*.json")) for r in resolve(p, conn)]
    for r in rows:
        extra = (f"actual {r['actual']:.2f}, median {r['p50']:.2f}, inside 80%: {r['inside_80']}, "
                 f"twin CRPS {r['crps']:.2f}, baselines {', '.join(f'{k} {v:.2f}' for k, v in r['baselines'].items())}"
                 if r["status"] == "resolved" else r["status"])
        print(f"{r['ticker']} {r['kpi']} {r['period']} [hash {'ok' if r['hash_ok'] else 'MISMATCH'}]: {extra}")
    OUT.write_text(to_markdown(rows), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
